"""Theme the retained screens without changing their responsive layout rules."""
from pathlib import Path
import re, colorsys
root=Path(__file__).resolve().parents[1]/'dist'
colors=set()
pattern=re.compile(r'#[0-9a-f]{8}(?![\w-])|#[0-9a-f]{6}(?![\w-])|#[0-9a-f]{4}(?![\w-])|#[0-9a-f]{3}(?![\w-])|var\(--rp-([0-9a-f]+)\)',re.I)
def replace(match):
    token=match.group(1) or match.group()[1:].lower()
    colors.add(token)
    return 'var(--rp-'+token+')'
for name in ['styles.css','discovery.css','entry.css','work-profile.css']:
    path=root/name
    path.write_text(pattern.sub(replace,path.read_text(encoding='utf-8')),encoding='utf-8')
def light(token):
    full=''.join(x*2 for x in token) if len(token) in [3,4] else token
    rgb=[int(full[i:i+2],16)/255 for i in [0,2,4]]
    h,l,s=colorsys.rgb_to_hls(*rgb)
    # Dark surfaces become off-white; pale type becomes deep blue. Accent and
    # interaction colours receive semantic overrides in visual-polish.css.
    target=.985-l*.22 if l<.55 else .17+(1-l)*.34
    rr=colorsys.hls_to_rgb(h,target,min(s,.65))
    return '#'+''.join(f'{round(v*255):02x}' for v in rr)+full[6:]
dark=';\n'.join('  --rp-'+c+':#'+c for c in sorted(colors))
bright=';\n'.join('  --rp-'+c+':'+light(c) for c in sorted(colors))
(root/'theme-palette.css').write_text('/* Generated by scripts/build-theme-palette.py. */\n:root {\n'+dark+';\n}\nhtml[data-theme="light"] {\n'+bright+';\n}\n',encoding='utf-8')
print(f'Theme bridge: {len(colors)} colours across retained screens.')
